import { cp, mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const project = fileURLToPath(new URL("../", import.meta.url));
const client = path.join(project, "client");
const metadata = path.join(project, "dist", ".openai");
const server = path.join(project, "dist", "server");
const portable = process.argv.includes("--portable");
const mediaTypes = {
  ".html": "text/html; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".svg": "image/svg+xml",
  ".webp": "image/webp",
};

const assets = {};
for (const file of (await readdir(client)).sort()) {
  const type = mediaTypes[path.extname(file)];
  if (!type) continue;
  const buffer = await readFile(path.join(client, file));
  assets[`/${file}`] = { type, data: buffer.toString("base64") };
}
if (!assets["/index.html"]) throw new Error("Folio needs a client/index.html file.");
const schema = await readFile(path.join(client, "ledger-schema.js"), "utf8");
const ledgerApi = await readFile(path.join(project, "worker", "ledger-api.mjs"), "utf8");
const worker = await readFile(path.join(project, "worker", "site.mjs"), "utf8");

await mkdir(server, { recursive: true });
if (!portable) {
  await mkdir(metadata, { recursive: true });
  await cp(path.join(project, ".openai", "hosting.json"), path.join(metadata, "hosting.json"));
  await cp(path.join(project, "drizzle"), path.join(metadata, "drizzle"), { recursive: true });
}
await writeFile(path.join(server, "index.js"), [
  "// Generated by scripts/build-worker.mjs.",
  schema,
  ledgerApi,
  `const folioAssets = ${JSON.stringify(assets)};`,
  worker,
].join("\n"));
console.log(`Built Folio Worker and ${Object.keys(assets).length} bundled assets.`);
